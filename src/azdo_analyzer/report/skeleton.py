"""Draft ``.gitlab-ci.yml`` skeletons (spec section 13.8). Drafts only - never production-ready."""

from __future__ import annotations

import json
import re

from ..config.models import Config
from ..model.entities import BuildPipeline, Estate, Job, ReleasePipeline, Stage, Trigger, iter_steps

HEADER = "# DRAFT generated by azdo-analyzer — review before use"


def q(text: str) -> str:
    """A YAML double-quoted scalar (JSON strings are valid YAML)."""
    return json.dumps(text, ensure_ascii=False)


def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-") or "job"


def env_name(name: str) -> str:
    cleaned = re.sub(r"[^A-Za-z0-9_]", "_", name).upper()
    return cleaned if re.match(r"^[A-Z_]", cleaned) else f"_{cleaned}"


def comment(text: str) -> str:
    return " ".join(text.split())


def _branch_condition(branch: str) -> str:
    if branch in ("*", ""):
        return "$CI_COMMIT_BRANCH"
    if "*" in branch:
        pattern = re.escape(branch).replace("\\*", ".*").replace("/", "\\/")
        return f"$CI_COMMIT_BRANCH =~ /^{pattern}$/"
    return f"$CI_COMMIT_BRANCH == {q(branch)}"


def _rules(triggers: list[Trigger]) -> list[str]:
    lines: list[str] = []
    for trigger in triggers:
        if "disabled" in trigger.detail:
            continue
        if trigger.type == "ci":
            for branch in trigger.branches_include or ["*"]:
                lines.append(f"    - if: {q(_branch_condition(branch))}")
                if trigger.paths_include:
                    lines.append("      changes:")
                    lines.extend(f"        - {q(path.strip('/').rstrip('*').rstrip('/') + '/**/*')}" for path in trigger.paths_include)
        elif trigger.type in ("pr", "gated"):
            lines.append('    - if: "$CI_PIPELINE_SOURCE == \\"merge_request_event\\""')
        elif trigger.type == "schedule":
            lines.append(
                f'    - if: "$CI_PIPELINE_SOURCE == \\"schedule\\""  # cron {comment(trigger.cron)} {comment(trigger.timezone)}: create a pipeline schedule'
            )
        elif trigger.type in ("build_completion", "pipeline_resource", "artifact"):
            lines.append(
                f'    - if: "$CI_PIPELINE_SOURCE == \\"pipeline\\""  # upstream {comment(trigger.upstream)}: add trigger:project there'
            )
    seen: set[str] = set()
    unique = []
    for line in lines:
        if line.startswith("    - if") and line in seen:
            continue
        seen.add(line)
        unique.append(line)
    return unique


def render_skeleton(pipeline: BuildPipeline | ReleasePipeline, estate: Estate, config: Config) -> str:
    plan = pipeline.plan
    groups = {g.id: g for g in estate.variable_groups}
    mapping = {(m.stage, m.job, m.task, m.display_name): m for m in plan.step_mappings}
    multi = isinstance(pipeline, ReleasePipeline) or len(pipeline.stages) > 1
    stages = plan.stages or ["build"]
    lines = [
        HEADER,
        f"# Source: {comment(pipeline.id)} ({'release' if isinstance(pipeline, ReleasePipeline) else pipeline.kind}) - status {pipeline.stats.status}, effort {pipeline.effort.band}",
        f"# Runner: {plan.runner_os}" + (f" ({comment('; '.join(plan.runner_reasons))})" if plan.runner_reasons else ""),
    ]
    lines += [f"# NOTE: {comment(note)}" for note in plan.notes]
    lines.append("")
    if plan.includes:
        lines.append("include:")
        for include in plan.includes:
            first = True
            for key, value in include.items():
                lines.append(f"  {'- ' if first else '  '}{key}: {q(value)}")
                first = False
        lines.append("")
    lines.append("stages:")
    lines += [f"  - {stage}" for stage in dict.fromkeys(stages)]
    lines.append("")

    rules = _rules(pipeline.triggers)
    if rules:
        lines += ["workflow:", "  rules:", *rules, ""]

    variables = [v for v in pipeline.variables if v.scope == "definition"]
    group_names = [groups[g].name for g in pipeline.variable_group_ids if g in groups]
    if variables or group_names:
        lines.append("variables:")
        emitted: set[str] = set()
        for variable in variables:
            key = env_name(variable.name)
            if variable.is_secret:
                lines.append(f"  # secret {comment(variable.name)}: create as a masked, protected CI/CD variable")
            elif key in emitted:
                # conditional (${{ if }}) variants of one variable: keep the first, note the rest
                lines.append(f"  # {key} also set to {comment(q(variable.value))} under a condition -> rules:variables")
            else:
                lines.append(f"  {key}: {q(variable.value)}")
                emitted.add(key)
        for name in group_names:
            lines.append(f"  # variable group {comment(name)}: recreate as group/project CI/CD variables")
        if not emitted:
            lines.append('  AZDO_MIGRATION_PLACEHOLDER: "remove-me"')
        lines.append("")

    used_names: set[str] = set()
    job_names: dict[tuple[str, str], str] = {}

    def unique_name(stage: Stage, job: Job) -> str:
        base = slug(f"{stage.display_name or stage.name}-{job.display_name or job.name}" if multi else (job.display_name or job.name))
        name, n = base, 1
        while name in used_names:
            n += 1
            name = f"{base}-{n}"
        used_names.add(name)
        job_names[(stage.name, job.name)] = name
        return name

    for index, stage in enumerate(pipeline.stages):
        gl_stage = stages[index] if multi and index < len(stages) else stages[0]
        tier = config.environments.deployment_tiers.get(stage.tier, "")
        manual = bool(stage.pre_approval and not stage.pre_approval.automated)
        for job in stage.jobs:
            name = unique_name(stage, job)
            label = job.display_name or job.name
            lines.append(f"{name}:")
            lines.append(f"  stage: {gl_stage}")
            if plan.runner_os == "linux" and plan.image and job.kind != "server":
                lines.append(f"  image: {q(job.container or plan.image)}")
            if plan.tags:
                lines.append("  tags: [" + ", ".join(q(t) for t in plan.tags) + "]")
            needs = [job_names[(stage.name, dep)] for dep in job.depends_on if (stage.name, dep) in job_names]
            if needs:
                lines.append("  needs: [" + ", ".join(q(n) for n in needs) + "]")
            if job.strategy:
                lines.append(f"  # strategy {comment(job.strategy)} {comment(', '.join(job.matrix))}: use parallel:matrix")
            if job.condition and job.condition != "succeeded()":
                lines.append(f"  # condition: {comment(job.condition)} -> rules:")
            if job.kind == "deployment_group":
                lines.append(
                    f"  # TODO(azdo:deployment-group) {comment(job.deployment_group)}: no GitLab equivalent - runner on target or WinRM/SSH/Ansible"
                )
            if stage.targets or isinstance(pipeline, ReleasePipeline) or job.kind == "deployment":
                environment = slug(job.environment or stage.display_name or stage.name)
                lines.append("  environment:")
                lines.append(f"    name: {q(environment)}")
                if tier:
                    lines.append(f"    deployment_tier: {tier}")
                if stage.parallelism:
                    lines.append(f"  resource_group: {q(environment)}")
            if manual or job.kind == "server":
                lines.append(
                    "  when: manual"
                    + ("  # pre-deployment approval -> protected environment + deployment approvals" if manual else "  # agentless phase")
                )
            if job.timeout:
                lines.append(f"  timeout: {job.timeout} minutes")
            lines.append("  script:")
            steps = iter_steps(job.steps)
            for step in steps:
                mapped = mapping.get((stage.display_name or stage.name, label, step.task_name, step.display_name))
                title = comment(step.display_name or step.task_name)
                if mapped is None or not mapped.mapped:
                    lines.append(f"    # TODO(azdo:{comment(step.task_name)}) {title}: no mapping - port manually")
                else:
                    hint = comment(mapped.script_hint or ", ".join(mapped.keywords))
                    lines.append(f"    # {comment(step.task_name)} ({title}): {comment(mapped.approach)} - {hint}")
            lines.append(f"    - echo {q(f'TODO: port {len(steps)} step(s) of {label}')}")
            lines.append("")
    if not any(stage.jobs for stage in pipeline.stages):
        lines += ["placeholder:", f"  stage: {stages[0]}", "  script:", '    - echo "TODO: definition has no jobs"', ""]
    return "\n".join(lines).rstrip() + "\n"
